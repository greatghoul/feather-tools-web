// Generates per-tool Astro page files and client island wrappers so each tool
// page statically imports only its own App (per-tool CSS/JS chunking, matching
// the legacy pipeline). Run after adding or renaming a tool:
//
//   node scripts/gen-tool-pages.mjs
//
// Outputs:
//   src/tools/<slug>/ToolIsland.tsx        - client island for the tool
//   src/pages/[lang]/<slug>.astro          - page that mounts it via ToolShell
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(scriptDir, '..');

// Every tool has an App.tsx root; generate its island + page from it.
const tools = readFileSync(resolve(ROOT, 'src/data/tools.ts'), 'utf8');
const slugs = [...tools.matchAll(/slug: '([a-z0-9-]+)'/g)].map((m) => m[1]).sort();

const islandTemplate = (slug) => `// Generated by scripts/gen-tool-pages.mjs — do not edit by hand.
import { createToolIsland } from '~/components/createToolIsland';
import App from './App';
import commonEn from '~/i18n/client/en.json';
import commonZh from '~/i18n/client/zh.json';
import toolEn from './i18n/en.json';
import toolZh from './i18n/zh.json';

export default createToolIsland(App, {
    en: { ...commonEn, ...toolEn },
    zh: { ...commonZh, ...toolZh },
});
`;

const pageTemplate = (slug) => `---
// Generated by scripts/gen-tool-pages.mjs — do not edit by hand.
import ToolShell from '../../components/ToolShell.astro';
import ToolIsland from '../../tools/${slug}/ToolIsland';
import { SITE, type Locale } from '../../data/site';

export function getStaticPaths() {
    return SITE.locales.map((lang) => ({ params: { lang } }));
}

const locale = Astro.params.lang as Locale;
---
<ToolShell slug="${slug}" locale={locale}>
    <ToolIsland client:load slot="app" locale={locale} />
</ToolShell>
`;

let islands = 0;
let pages = 0;
for (const slug of slugs) {
    const app = resolve(ROOT, 'src/tools', slug, 'App.tsx');
    if (!existsSync(app)) continue;

    const islandPath = resolve(ROOT, 'src/tools', slug, 'ToolIsland.tsx');
    writeFileSync(islandPath, islandTemplate(slug));
    islands++;

    const pageDir = resolve(ROOT, 'src/pages/[lang]');
    mkdirSync(pageDir, { recursive: true });
    writeFileSync(resolve(pageDir, `${slug}.astro`), pageTemplate(slug));
    pages++;
}
console.log(`generated ${islands} ToolIsland.tsx and ${pages} pages`);
