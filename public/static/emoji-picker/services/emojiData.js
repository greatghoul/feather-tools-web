const EMOJI_BY_CHAR = new Map();
for (const category of CATEGORIES) {
    for (const emoji of EMOJIS[category.id]) {
        EMOJI_BY_CHAR.set(emoji.char, emoji);
    }
}

export function getEmojiByChar(char) {
    return EMOJI_BY_CHAR.get(char);
}

export function getEmojiName(emoji) {
    if (emoji.nameZh && typeof window !== 'undefined' && window.LOCALE && window.LOCALE.startsWith('zh')) {
        return emoji.nameZh;
    }
    return emoji.name;
}

const isWindows = typeof navigator !== 'undefined'
    && /Windows/i.test(navigator.userAgent || navigator.platform || '');

/**
 * Filters out emojis that are not supported on the current platform.
 * Country flag emojis (regional indicators) do not render on Windows.
 *
 * @param {Array} emojis - The emoji list to filter.
 * @returns {Array}
 */
export function filterPlatformSupported(emojis) {
    if (!isWindows || !Array.isArray(emojis)) {
        return emojis;
    }
    return emojis.filter((emoji) => !emoji.unsupportedOnWindows);
}

export function searchEmojis(query) {
    if (!query || !query.trim()) {
        return null;
    }
    const q = query.trim().toLowerCase();
    const results = [];
    for (const category of CATEGORIES) {
        for (const emoji of EMOJIS[category.id]) {
            const haystack = `${emoji.name} ${emoji.nameZh} ${emoji.keywords}`.toLowerCase();
            if (haystack.includes(q)) {
                results.push(emoji);
            }
        }
    }
    return results;
}
